#!/usr/bin/env python3
"""Precompute window, twiddle and bit-reversal tables as C const data.

    python3 cdsp/tools/gen_tables.py --n-fft 4096 --env-n-fft 1024 \
        --window hann --out hardware/<kit>/firmware/model/pdm_tables.h

Why: on a RAM-constrained part these tables are the largest avoidable
allocation. For a 4096-point pipeline with a 1024-point envelope stage they are

    window    4096 x 4 B = 16 384
    twiddle   4098 x 4 B = 16 392
    bitrev    2048 x 2 B =  4 096
    env tables             = 10 248
                            -------
                             47 120 B

On the nRF9160 (256 kB, of which Zephyr and the modem library take ~65 kB) that
is the difference between the pipeline fitting with 90 kB spare and fitting with
40 kB spare. Moving them to flash costs 47 kB of a 1 MB part and about 3 % on
the FFT, because flash reads are a couple of cycles slower than RAM on the M33
bus -- 0.4 ms out of 14 ms.

It also removes ~40 ms of boot-time transcendentals (4096 cosines, 3072 sin/cos
pairs, and the Butterworth design), which matters for a kit that wakes from a
RAM-losing sleep mode: there, the init cost is paid every cycle.

The values are generated by the same code the runtime uses
(`pdmcore.dsp.windows.window` and the twiddle recurrence in `pdm_rfft_init`), so
the precomputed tables are bit-identical to the computed ones -- asserted by
`cdsp/tests/test_tables.c`.
"""

from __future__ import annotations

import argparse
import math
import os
import sys
from typing import List, Optional, Sequence

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_HERE, "..", "..", "core")))

import numpy as np  # noqa: E402

from pdmcore.dsp.windows import WINDOW_NAMES, window  # noqa: E402

WINDOW_ENUM = {
    "rect": "PDM_WIN_RECT", "hann": "PDM_WIN_HANN", "hamming": "PDM_WIN_HAMMING",
    "blackman": "PDM_WIN_BLACKMAN", "blackman_harris": "PDM_WIN_BLACKMAN_HARRIS",
    "flattop": "PDM_WIN_FLATTOP",
}

#: The enum values, as integers. The preprocessor cannot see a C enum, so a
#: `#if PDM_TABLES_WINDOW != APP_WINDOW` comparing enum *names* silently
#: evaluates both to 0 and the guard never fires -- or, with -Wundef -Werror,
#: fails the build with a confusing message. Comparing integer IDs works.
WINDOW_ID = {
    "rect": 0, "hann": 1, "hamming": 2, "blackman": 3,
    "blackman_harris": 4, "flattop": 5,
}


def c_floats(name: str, values: Sequence[float], per_line: int = 6) -> str:
    vals = [f"{float(v):.9e}f" for v in values]
    lines = ["    " + ", ".join(vals[i:i + per_line]) + ","
             for i in range(0, len(vals), per_line)]
    return (f"static const float {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n")


def c_u16(name: str, values: Sequence[int], per_line: int = 16) -> str:
    vals = [str(int(v)) for v in values]
    lines = ["    " + ", ".join(vals[i:i + per_line]) + ","
             for i in range(0, len(vals), per_line)]
    return (f"static const uint16_t {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n")


def twiddle_and_bitrev(n: int):
    """Exactly what pdm_rfft_init computes, in the same layout."""
    half = n // 2
    two_pi = 2.0 * math.pi
    tw: List[float] = [0.0] * (n + 2)
    for k in range(half // 2):
        ang = -two_pi * k / half
        tw[2 * k] = math.cos(ang)
        tw[2 * k + 1] = math.sin(ang)
    for k in range(half // 2 + 1):
        ang = -two_pi * k / n
        tw[half + 2 * k] = math.cos(ang)
        tw[half + 2 * k + 1] = math.sin(ang)
    bits = max(1, (half - 1).bit_length())
    br = []
    for i in range(half):
        r = 0
        for b in range(bits):
            if i & (1 << b):
                r |= 1 << (bits - 1 - b)
        br.append(r)
    return tw, br


def emit(n_fft: int, env_n_fft: int, win_name: str) -> str:
    out: List[str] = []
    w = out.append
    w("/* GENERATED by cdsp/tools/gen_tables.py -- do not edit.")
    w(" *")
    w(f" * Precomputed {win_name} window, FFT twiddle and bit-reversal tables for")
    w(f" * n_fft={n_fft} and envelope n_fft={env_n_fft}, as `const` so they live in")
    w(" * flash rather than RAM.")
    w(" *")
    w(" * Bit-identical to what pdm_window_make and pdm_rfft_init compute at")
    w(" * runtime -- asserted by cdsp/tests/test_tables.c. Regenerate with")
    w(" * `make -C cdsp tables N_FFT=... ENV_N_FFT=... WINDOW=...`.")
    w(" */")
    w("")
    w("#ifndef PDM_TABLES_H")
    w("#define PDM_TABLES_H")
    w("")
    w("#include <stdint.h>")
    w("")
    w(f"#define PDM_TABLES_N_FFT     {n_fft}")
    w(f"#define PDM_TABLES_ENV_N_FFT {env_n_fft}")
    w(f"#define PDM_TABLES_WINDOW    {WINDOW_ENUM[win_name]}")
    w(f"#define PDM_TABLES_WINDOW_ID {WINDOW_ID[win_name]}   /* for #if guards */")
    w("")

    total = 0
    for tag, size in (("", n_fft), ("_env", env_n_fft)):
        spec = window(win_name, size)
        tw, br = twiddle_and_bitrev(size)
        w(f"/* --- n = {size} --- */")
        w(f"#define PDM_TABLES{tag.upper()}_COHERENT_GAIN {spec.coherent_gain:.9e}f")
        w(f"#define PDM_TABLES{tag.upper()}_ENBW_BINS     {spec.enbw_bins:.9e}f")
        w(f"#define PDM_TABLES{tag.upper()}_SUM           {float(np.sum(spec.coeff)):.9e}f")
        w(f"#define PDM_TABLES{tag.upper()}_SUM_SQ        {float(np.sum(spec.coeff ** 2)):.9e}f")
        w(c_floats(f"pdm_table_window{tag}", spec.coeff))
        w(c_floats(f"pdm_table_twiddle{tag}", tw))
        w(c_u16(f"pdm_table_bitrev{tag}", br))
        total += 4 * size + 4 * len(tw) + 2 * len(br)
        w("")

    w(f"/* Total flash cost: {total} bytes ({total / 1024.0:.1f} kB), which is the")
    w(" * same amount of RAM saved. */")
    w(f"#define PDM_TABLES_FLASH_BYTES {total}")
    w("")
    w("#endif /* PDM_TABLES_H */")
    return "\n".join(out) + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n-fft", type=int, default=4096)
    ap.add_argument("--env-n-fft", type=int, default=1024)
    ap.add_argument("--window", default="hann", choices=sorted(WINDOW_ENUM))
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    for n in (args.n_fft, args.env_n_fft):
        if n & (n - 1) or n < 64:
            raise SystemExit(f"{n} is not a power of two >= 64")
    if args.window not in WINDOW_NAMES:
        raise SystemExit(f"unknown window {args.window}")

    text = emit(args.n_fft, args.env_n_fft, args.window)
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write(text)
    print(f"wrote {args.out} ({os.path.getsize(args.out)} B source, "
          f"{text.count('PDM_TABLES_FLASH_BYTES') and ''}"
          f"{[l for l in text.splitlines() if 'FLASH_BYTES' in l][-1].split()[-1]} B of flash)",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
