#!/usr/bin/env python3
"""Generate cdsp/include/pdm_features_layout.h from pdmcore.features.

The feature vector's *layout* -- how many features, and the offset of each
block -- is a contract, and a contract that exists twice will eventually exist
in two versions. Generating the C side from the Python side makes that
impossible: if the layout changes, this header changes, and the firmware either
rebuilds against it or fails to compile.

    python3 cdsp/tools/gen_feature_layout.py --out cdsp/include/pdm_features_layout.h
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import List, Optional, Sequence

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(_HERE, "..", "..", "core")))

from pdmcore import FEATURE_SPEC_VERSION  # noqa: E402
from pdmcore.dsp.bearing import BEARING_CATALOG  # noqa: E402
from pdmcore.features import FeatureConfig, FeatureExtractor  # noqa: E402


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    fx = FeatureExtractor(FeatureConfig(bearing=BEARING_CATALOG["SKF6205"]))
    names = list(fx.names)

    # First index of each block. The blocks are contiguous by construction in
    # FeatureExtractor._build_names; this asserts that rather than assuming it,
    # because the firmware writes into them by offset.
    blocks = {}
    for i, n in enumerate(names):
        prefix = n.split(".")[0]
        blocks.setdefault(prefix, []).append(i)
    for prefix, idx in blocks.items():
        if idx != list(range(idx[0], idx[0] + len(idx))):
            raise SystemExit(
                f"feature block {prefix!r} is not contiguous: {idx[:5]}... "
                f"the firmware writes blocks by offset and cannot handle this"
            )

    out: List[str] = []
    w = out.append
    w("/* GENERATED by cdsp/tools/gen_feature_layout.py -- do not edit.")
    w(" *")
    w(" * The feature layout is a contract between firmware and cloud. Generating")
    w(" * the C side from pdmcore.features makes a silent divergence impossible:")
    w(" * change the layout and this header changes, so the firmware either")
    w(" * rebuilds against it or fails to compile.")
    w(" *")
    w(" * Regenerate with `make -C cdsp layout`.")
    w(" */")
    w("")
    w("#ifndef PDM_FEATURES_LAYOUT_H")
    w("#define PDM_FEATURES_LAYOUT_H")
    w("")
    w(f"#define PDM_FEATURE_SPEC_VERSION_GEN {FEATURE_SPEC_VERSION}")
    w(f"#define PDM_N_FEATURES {len(names)}")
    w("")
    for prefix in ("time", "band", "shape", "iso", "order", "bearing"):
        idx = blocks.get(prefix)
        if not idx:
            continue
        w(f"#define PDM_IDX_{prefix.upper():<8s} {idx[0]:3d}   /* {len(idx)} features */")
        w(f"#define PDM_N_{prefix.upper():<10s} {len(idx):3d}")
    w("")
    w("/* Guard: the layout header and the library must agree on the spec version. */")
    w("#if defined(PDM_FEATURE_SPEC_VERSION) && \\")
    w("    (PDM_FEATURE_SPEC_VERSION != PDM_FEATURE_SPEC_VERSION_GEN)")
    w("#error \"pdm_dsp.h and pdm_features_layout.h disagree on the feature spec version\"")
    w("#endif")
    w("")
    w("#ifdef PDM_WANT_FEATURE_NAMES")
    w(f"static const char *const pdm_feature_names[PDM_N_FEATURES] = {{")
    for n in names:
        w(f'    "{n}",')
    w("};")
    w("#endif")
    w("")
    w("#endif /* PDM_FEATURES_LAYOUT_H */")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {args.out}: {len(names)} features, blocks "
          + ", ".join(f"{k}@{v[0]}" for k, v in blocks.items()), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
