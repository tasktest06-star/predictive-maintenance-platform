#!/usr/bin/env python3
"""Generate cdsp/tests/golden.h from the pdmcore Python reference.

This is the mechanism that keeps the firmware and the cloud computing the same
number. The Python implementation is the reference; this script evaluates it on
fixed inputs and emits the results as C arrays, and `make -C cdsp test`
re-computes them in C and compares. The comparison runs natively on the build
host, so it gates every commit without hardware in the loop.

Tolerances are stated per check in test_cdsp.c and justified there. They are not
"close enough" -- they are the expected float32 accumulation error for the
specific operation, so a tolerance that has to be loosened is a signal that
something changed, not a nuisance.

    python3 cdsp/tools/gen_golden.py --out cdsp/tests/golden.h
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import Iterable, List, Sequence

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.abspath(os.path.join(HERE, "..", "..", "core")))

from pdmcore.dsp import windows as win_mod            # noqa: E402
from pdmcore.dsp.bearing import BEARING_CATALOG, fault_frequencies, harmonic_energy_ratio  # noqa: E402
from pdmcore.dsp.features import running_stats, time_features  # noqa: E402
from pdmcore.dsp.iso import iso_zone                  # noqa: E402
from pdmcore.dsp.spectrum import Spectrum, spectrum   # noqa: E402

FS = 25600.0
N_FFT = 256          # small enough to embed, large enough to exercise the split stage
N_BLOCK = 2048

WINDOW_KINDS = ["rect", "hann", "hamming", "blackman", "blackman_harris", "flattop"]


def c_float_array(name: str, values: Iterable[float], per_line: int = 6) -> str:
    vals = [f"{float(v):.9e}f" for v in values]
    lines: List[str] = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(vals[i : i + per_line]) + ",")
    return f"static const float {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def c_int_array(name: str, values: Sequence[int], ctype: str = "int8_t", per_line: int = 16) -> str:
    vals = [str(int(v)) for v in values]
    lines: List[str] = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(vals[i : i + per_line]) + ",")
    return f"static const {ctype} {name}[{len(vals)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    out: List[str] = []
    w = out.append
    w("/* GENERATED by cdsp/tools/gen_golden.py from the pdmcore reference.")
    w(" * DO NOT EDIT. Regenerate with `make -C cdsp golden`.")
    w(" *")
    w(" * Every value here was produced by the Python implementation in")
    w(" * core/pdmcore. The C implementation is checked against them by")
    w(" * tests/test_cdsp.c. If a value changes, the two implementations have")
    w(" * diverged and one of them is wrong -- which is the entire point.")
    w(" */")
    w("")
    w("#ifndef PDM_GOLDEN_H")
    w("#define PDM_GOLDEN_H")
    w("")
    w("#include <stdint.h>")
    w("")
    w(f"#define GOLD_FS        {FS:.1f}f")
    w(f"#define GOLD_N_FFT     {N_FFT}")
    w(f"#define GOLD_N_BINS    {N_FFT // 2 + 1}")
    w(f"#define GOLD_N_BLOCK   {N_BLOCK}")
    w("")

    # ---------------------------------------------------------------- windows
    w("/* --- windows: coefficients (n=32 prefix), coherent gain, ENBW --- */")
    cg: List[float] = []
    enbw: List[float] = []
    for name in WINDOW_KINDS:
        spec = win_mod.window(name, N_FFT)
        cg.append(spec.coherent_gain)
        enbw.append(spec.enbw_bins)
        w(c_float_array(f"gold_win_{name}_head", spec.coeff[:32]))
    w(c_float_array("gold_win_cg", cg))
    w(c_float_array("gold_win_enbw", enbw))
    w("")

    # -------------------------------------------------------------- test signal
    # A deterministic mixture: two tones at non-bin-centre frequencies, an
    # impulse train, and pseudo-random noise. Exercises tonal accuracy, the
    # impulsive path and the noise floor in one vector.
    rng = np.random.default_rng(12345)
    t = np.arange(N_BLOCK) / FS
    df = FS / N_FFT
    sig = (
        1.0 * np.sin(2 * np.pi * (10.37 * df) * t)
        + 0.25 * np.sin(2 * np.pi * (40.5 * df) * t + 0.7)
        + 0.05 * rng.standard_normal(N_BLOCK)
    )
    for start in range(37, N_BLOCK - 40, 311):
        k = np.arange(40)
        sig[start : start + 40] += 0.8 * np.exp(-0.08 * k) * np.sin(0.9 * k)
    sig = sig.astype(np.float64)
    w("/* --- the shared test signal (deterministic) --- */")
    w(c_float_array("gold_signal", sig))
    w("")

    # ------------------------------------------------------------------- rFFT
    # Raw magnitudes of an unwindowed, non-detrended 256-sample block, which is
    # exactly what pdm_rfft + pdm_rfft_magnitude produce.
    block = sig[:N_FFT]
    mag = np.abs(np.fft.rfft(block))
    w("/* --- |rfft| of gold_signal[0:256], unwindowed, no detrend --- */")
    w(c_float_array("gold_rfft_mag", mag))
    w("")

    # -------------------------------------------------------------- spectrum
    # Hann-windowed, mean-removed, single-block spectrum in each scaling, plus
    # the band RMS invariants that pin the calibration.
    hann = win_mod.window("hann", N_FFT)
    blk = (block - np.mean(block)) * hann.coeff
    raw = np.abs(np.fft.rfft(blk))
    specs = {}
    for scaling in ("peak", "rms", "power", "psd"):
        sp = spectrum(block, FS, n_fft=N_FFT, window_name="hann", scaling=scaling,
                      detrend="mean", overlap=0.0)
        specs[scaling] = sp
        w(c_float_array(f"gold_spec_{scaling}", sp.value))
    w(c_float_array("gold_hann_raw_mag", raw))
    w("")

    bands = [(0.0, FS / 2), (0.0, 2000.0), (2000.0, 6000.0), (6000.0, 12800.0)]
    w("/* --- band RMS per scaling over 4 bands (the calibration invariant) --- */")
    w(c_float_array("gold_band_edges", [v for b in bands for v in b]))
    for scaling in ("peak", "rms", "power", "psd"):
        sp = specs[scaling]
        w(c_float_array(f"gold_band_rms_{scaling}", [sp.rms_in_band(lo, hi) for lo, hi in bands]))
    w(f"#define GOLD_TIME_RMS  {float(np.sqrt(np.mean((block - np.mean(block)) ** 2))):.9e}f")
    w("")

    # -------------------------------------------------------- time features
    tf = time_features(sig)
    rs = running_stats(sig - np.mean(sig))
    w("/* --- time-domain indicators of the full block --- */")
    names = ["mean", "rms", "std", "peak", "peak_to_peak", "crest", "kurtosis",
             "skewness", "shape", "impulse", "clearance", "margin", "zcr", "entropy"]
    w(c_float_array("gold_time_features", [getattr(tf, n) for n in names]))
    w("/* order: " + ", ".join(names) + " */")
    w(c_float_array("gold_running_stats",
                    [rs["mean"], rs["std"], rs["rms"], rs["peak"], rs["kurtosis"],
                     rs["skewness"], rs["crest"], rs["mean_abs"], rs["clearance"]]))
    w("/* order: mean, std, rms, peak, kurtosis, skewness, crest, mean_abs, clearance */")
    w("")

    # ------------------------------------------------------------- bearing
    geom = BEARING_CATALOG["SKF6205"]
    shaft = 29.6667
    ff = fault_frequencies(geom, shaft)
    w("/* --- SKF6205 at 29.6667 Hz: shaft, FTF, BPFO, BPFI, BSF --- */")
    w(c_float_array("gold_fault_freqs",
                    [ff.shaft_hz, ff.ftf_hz, ff.bpfo_hz, ff.bpfi_hz, ff.bsf_hz]))
    w(f"#define GOLD_BEARING_N_BALLS   {float(geom.n_balls):.9e}f")
    w(f"#define GOLD_BEARING_BALL_D    {float(geom.ball_d):.9e}f")
    w(f"#define GOLD_BEARING_PITCH_D   {float(geom.pitch_d):.9e}f")
    w(f"#define GOLD_BEARING_ANGLE     {float(geom.contact_angle_deg):.9e}f")
    w(f"#define GOLD_SHAFT_HZ          {shaft:.9e}f")
    w("")

    # Harmonic SNR on a synthetic envelope spectrum with a planted BPFO family.
    n_env = 512
    df_env = 2500.0 / n_env
    env = 0.02 + 0.01 * np.abs(rng.standard_normal(n_env))
    bpfo = ff.bpfo_hz
    for h in range(1, 6):
        idx = int(round(bpfo * h / df_env))
        if 0 < idx < n_env:
            env[idx] += 0.45 / h
    env = env.astype(np.float64)
    env_spec = Spectrum(freq_hz=np.arange(n_env) * df_env, value=env, scaling="peak",
                        fs_hz=2500.0, n_fft=2 * (n_env - 1), n_averages=1,
                        window_name="hann", enbw_hz=1.5 * df_env)
    hr_hit = harmonic_energy_ratio(env_spec, bpfo, n_harmonics=5, rel_tol=0.02,
                                   floor_width_hz=120.0)
    hr_miss = harmonic_energy_ratio(env_spec, ff.bpfi_hz, n_harmonics=5, rel_tol=0.02,
                                    floor_width_hz=120.0)
    w("/* --- synthetic envelope spectrum with a planted BPFO family --- */")
    w(f"#define GOLD_ENV_N      {n_env}")
    w(f"#define GOLD_ENV_DF     {df_env:.9e}f")
    w(c_float_array("gold_env_spec", env))
    w(f"#define GOLD_SNR_BPFO   {hr_hit['ratio']:.9e}f")
    w(f"#define GOLD_SNR_BPFI   {hr_miss['ratio']:.9e}f")
    w(f"#define GOLD_MATCHED_BPFO  {int(hr_hit['n_matched'])}")
    w("")

    # ----------------------------------------------------------------- ISO
    iso_inputs = [0.5, 1.4, 1.41, 2.8, 2.9, 4.5, 4.6, 9.0]
    w("/* --- ISO 20816-3 zone boundaries, group2_rigid --- */")
    w(c_float_array("gold_iso_inputs", iso_inputs))
    w(c_int_array("gold_iso_zones",
                  ["ABCD".index(iso_zone(v, "group2_rigid")) for v in iso_inputs],
                  ctype="uint8_t"))
    w("")

    # --------------------------------------------------------------- model
    # A fixed, deliberately small int8 model with a known score, so the firmware
    # inference path is pinned independently of any training run.
    n_feat, h1, h2 = 8, 6, 4
    mrng = np.random.default_rng(7)
    w1 = mrng.integers(-100, 100, size=(n_feat, h1)).astype(np.int8)
    w2 = mrng.integers(-100, 100, size=(h1, h2)).astype(np.int8)
    s1, s2 = 0.0125, 0.0175
    centre = np.array([0.3, -0.2, 0.15, 0.05])
    in_centre = np.linspace(-1.0, 1.0, n_feat)
    in_scale = np.linspace(0.5, 2.0, n_feat)
    feats = np.array([0.4, -1.2, 0.9, 2.1, -0.3, 1.7, 0.0, -2.4])

    # Reference forward pass, mirroring pdm_model_score including its on-the-fly
    # int8 input quantisation at 1/16 -- the C path quantises, so the reference
    # must too or the comparison is meaningless.
    z = (feats - in_centre) / in_scale
    cur = z
    for wq, sc, last in ((w1, s1, False), (w2, s2, True)):
        xq = np.clip(np.round(cur * 16.0), -128, 127)
        acc = xq @ wq.astype(np.int32)
        y = acc * sc / 16.0
        if not last:
            y = np.where(y < 0, y * 0.1, y)
        cur = y
    score = float(np.sqrt(np.sum((cur - centre) ** 2)))

    w("/* --- fixed int8 model, pins the firmware inference path --- */")
    w(f"#define GOLD_MODEL_N_FEAT  {n_feat}")
    w(f"#define GOLD_MODEL_H1      {h1}")
    w(f"#define GOLD_MODEL_H2      {h2}")
    w(f"#define GOLD_MODEL_S1      {s1:.9e}f")
    w(f"#define GOLD_MODEL_S2      {s2:.9e}f")
    w(f"#define GOLD_MODEL_LEAK    1.000000000e-01f")
    w(c_int_array("gold_model_w1", w1.ravel(order="C")))
    w(c_int_array("gold_model_w2", w2.ravel(order="C")))
    w(c_float_array("gold_model_centre", centre))
    w(c_float_array("gold_model_in_centre", in_centre))
    w(c_float_array("gold_model_in_scale", in_scale))
    w(c_float_array("gold_model_features", feats))
    w(f"#define GOLD_MODEL_SCORE   {score:.9e}f")
    w("")
    w("#endif /* PDM_GOLDEN_H */")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {args.out} ({os.path.getsize(args.out)} bytes)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
