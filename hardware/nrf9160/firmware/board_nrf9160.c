/* ------------------------------------------------------------------ sleep */
uint32_t pdm_board_sleep_ms(uint32_t ms)
{
    if (ms == 0u) {
        return 0u;
    }
    /* k_msleep with Zephyr's PM enabled puts the SoC into System ON idle with
     * the modem in PSM: roughly 3 uA, SRAM retained, and -- critically -- the
     * modem stays REGISTERED.
     *
     * System OFF would reach ~2 uA but drops the registration, so the next
     * transmission pays a full LTE attach (~1000 mA.s) instead of an RRC
     * connection (~95 mA.s). Saving 1 uA to spend 900 mA.s is a bad trade at
     * any interval under about a year.
     */
    k_msleep((int32_t)ms);
    return ms;
}

void pdm_board_identify(uint32_t seconds)
{
    for (uint32_t i = 0; i < seconds * 4u; ++i) {
        (void)gpio_pin_toggle_dt(&s_led);
        k_msleep(250);
    }
    (void)gpio_pin_set_dt(&s_led, 0);
}

void pdm_board_watchdog_feed(void)
{
    if (s_wdt_channel >= 0) {
        (void)wdt_feed(s_wdt, s_wdt_channel);
    }
}
