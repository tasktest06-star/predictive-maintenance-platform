/* board_nrf9160.c -- pdm_board.h for the Nordic nRF9160 DK + IIS3DWB.
 *
 * Target: nRF9160 SiP (Cortex-M33 @ 64 MHz, 1 MB flash, 256 kB RAM) with an
 *         integrated LTE-M/NB-IoT modem and GNSS. nRF Connect SDK (Zephyr).
 * Sensor: IIS3DWB on SPI3 (the DK's ADXL362 is retained for the wake-on-motion
 *         path only -- it cannot do condition monitoring, see the README).
 *
 * THIS CODE HAS NOT RUN ON HARDWARE.
 *
 * Two things make this driver different from the other MCU kits, and both come
 * from the 256 kB of RAM:
 *
 * 1. **There is no raw staging buffer.** The other kits read the sensor FIFO
 *    into an int16 block and convert it to float afterwards, which costs
 *    48 kB for an 8192-sample acquisition. Here each FIFO chunk is converted to
 *    float as it arrives, straight into the caller's buffer, using a 512-sample
 *    scratch that is reused. Saves 48 kB and costs nothing -- the conversion
 *    was going to happen anyway. Every kit should do this; this one had to.
 *
 * 2. **The window and twiddle tables are in flash** (PDM_TABLES_IN_FLASH),
 *    saving another 46 kB. Generated by cdsp/tools/gen_tables.py.
 *
 * Together those two take the pipeline from ~168 kB to ~101 kB, which is the
 * difference between leaving 20 kB for Zephyr plus the modem library and
 * leaving 90 kB.
 */

